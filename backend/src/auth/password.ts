/**
 * Password hashing via argon2id, tuned to OWASP 2023+ recommendations for
 * argon2id: 19 MiB, 2 iterations, parallelism 1. See:
 *   https://cheatsheetseries.owasp.org/cheatsheets/Password_Storage_Cheat_Sheet.html
 *
 * We store the *encoded* argon2 string (contains algorithm, params, salt, hash)
 * so we can transparently upgrade parameters later — `verify()` reads the
 * embedded params from the stored hash.
 */
import * as argon2 from 'argon2';

/**
 * Deliberate defaults. Tune upward if you have CPU headroom.
 * - memoryCost: 19 MiB (OWASP min for argon2id).
 * - timeCost:   2 iterations (OWASP min).
 * - parallelism: 1 (single-thread, fine for Node's worker).
 * - hashLength: 32 bytes (256 bits, matches Ed25519 key size).
 * - saltLength: 16 bytes (128 bits, generated by argon2 lib).
 */
const HASH_OPTIONS: argon2.Options = {
  type: argon2.argon2id,
  memoryCost: 19 * 1024,
  timeCost: 2,
  parallelism: 1,
  hashLength: 32,
};

/**
 * Hash a plaintext password. Returns the argon2 encoded string, which is safe
 * to persist as-is (no separate salt column needed — encoded string embeds it).
 */
export async function hashPassword(password: string): Promise<string> {
  if (typeof password !== 'string' || password.length < 1) {
    throw new Error('password must be a non-empty string');
  }
  return argon2.hash(password, HASH_OPTIONS);
}

/**
 * Verify a plaintext password against a stored argon2 encoded hash. Returns
 * `false` (not throws) for any malformed input — timing-safe under the hood.
 */
export async function verifyPassword(stored: string, submitted: string): Promise<boolean> {
  if (typeof stored !== 'string' || typeof submitted !== 'string') return false;
  if (stored.length === 0 || submitted.length === 0) return false;
  try {
    return await argon2.verify(stored, submitted);
  } catch {
    return false;
  }
}

/**
 * Quick sanity policy — deliberately lenient (NIST 800-63B): length matters,
 * arbitrary "must have symbol" rules do NOT. Rejects obviously broken input.
 */
export function validatePasswordPolicy(password: string): { ok: true } | { ok: false; reason: string } {
  if (typeof password !== 'string') return { ok: false, reason: 'password must be a string' };
  if (password.length < 8) return { ok: false, reason: 'password must be at least 8 characters' };
  if (password.length > 256) return { ok: false, reason: 'password must be 256 characters or fewer' };
  // strip trivial patterns
  if (/^(.)\1+$/.test(password)) return { ok: false, reason: 'password cannot be a single repeated character' };
  return { ok: true };
}
