-- F5 — Tiled layer contract, part 2: pre-computed walkable mask on dungeons.
--
-- Every dungeon can carry a JSON array of walkable tile positions, computed
-- at import time (union of positions of every dungeon_tiles row whose
-- layer_kind is walkable — 'floor', 'doors', 'hidden'). moveRun uses this as
-- a Set<"x,y"> lookup instead of running one SQL_GET_TILE per move.
--
-- The column is NULLABLE. Legacy dungeons (imported before this migration)
-- have no mask yet — moveRun falls back to the SQL_GET_TILE path for those
-- until their tiles are re-saved (via admin edit or Tiled re-import), at
-- which point the mask is populated. Once populated, it never goes back to
-- NULL. This lets us ship without a bulk backfill; the population happens
-- lazily as dungeons are touched.
--
-- The value is `[[x1,y1],[x2,y2],...]` — a JSON array of two-element integer
-- arrays. Portable across SQLite and Postgres (both store it as TEXT).
ALTER TABLE dungeons ADD COLUMN walkable_mask_json TEXT;
