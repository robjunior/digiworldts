-- F5 — Tiled layer contract, part 1: per-tile layer classification.
--
-- Every dungeon_tiles row now carries a `layer_kind` marker that identifies
-- which TMJ tile layer the row came from. Legacy rows are all treated as
-- 'floor' (the previous importer only kept the "walkable" layer, which was
-- de-facto the floor plan). New imports classify each layer by name (case-
-- insensitive match against the enum), or by a per-layer `dw_kind` custom
-- property that overrides the name convention.
--
-- Portable across SQLite and Postgres — plain ALTER TABLE with DEFAULT +
-- CHECK. All existing rows fall into the DEFAULT bucket, so this migration
-- is safe to apply to any live DB in a single tx.
--
-- Layer kinds and their walkability semantics (interpreted in moveRun /
-- import):
--   floor        → walkable
--   doors        → walkable (blocking layer handled by dungeon_doors)
--   walls        → NOT walkable, purely visual
--   water        → NOT walkable, purely visual (swimming is not modeled)
--   pit          → NOT walkable, purely visual (trap handled by dungeon_traps)
--   decoration   → NOT walkable, overlay
--   hidden       → walkable in the mask; renderer draws it dimmed / hidden
ALTER TABLE dungeon_tiles ADD COLUMN layer_kind TEXT NOT NULL DEFAULT 'floor'
  CHECK (layer_kind IN ('floor', 'walls', 'doors', 'water', 'pit', 'decoration', 'hidden'));
