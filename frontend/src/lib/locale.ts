const DICTS: Record<Locale, Translations> = { en: EN, pt: PT };

/**
 * Translate a key. Falls back to English then to the key itself. Supports
 * {placeholder} interpolation. Called `t` to match common i18n convention.
 *
 * Locale is read via `getLocale()` at call time — components should wrap in
 * `useLocale()` for reactive re-render.
 */
export function t(key: string, params?: Readonly<Record<string, string | number>>): string {
  const locale = getLocale();
  const dict = DICTS[locale] ?? EN;
  const raw = dict[key] ?? EN[key] ?? key;
  if (params === undefined) return raw;
  let out = raw;
  for (const [k, v] of Object.entries(params)) {
    out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return out;
}
