#!/usr/bin/env bash
# scripts/materialize-env.sh
#
# Materialize a `.env` file from the CALLER's process environment.
#
# Reads a well-known list of DigiWorld env variables from the current process
# environment and writes them, in the same shape as `.env.example`, to the
# path in $OUTPUT_ENV_FILE (default: `.env` in CWD).
#
# Intended primarily for GitHub Actions deploy workflows: the workflow maps
# `secrets.X` and `vars.X` into a job step's `env:` block, then invokes this
# script — so no secret ever hits the shell command line or the workflow log.
#
# Fails LOUD if any REQUIRED variable is unset or empty. This is the last-mile
# guard against the "deployed with an empty MP_PAYER_EMAIL and blew up on /buy
# confirm" bug.
#
# Usage:
#   ./scripts/materialize-env.sh
#   OUTPUT_ENV_FILE=/tmp/foo.env ./scripts/materialize-env.sh

set -euo pipefail

OUTPUT="${OUTPUT_ENV_FILE:-.env}"

# ─── Required: unset or empty aborts the deploy ─────────────────────────────
REQUIRED=(
  POSTGRES_PASSWORD
  REDIS_PASSWORD
  SESSION_SECRET
  DISCORD_PUBLIC_URL
  GAME_PUBLIC_URL
  SERVICE_TOKEN_DISCORD
  DISCORD_TOKEN
  DISCORD_CLIENT_ID
  DISCORD_CLIENT_SECRET
  DISCORD_GUILD_ID
  MP_ACCESS_TOKEN
  MP_WEBHOOK_SECRET
  MP_PAYER_EMAIL
  MP_PAYER_NAME
  MP_PAYER_LAST_NAME
  MP_PAYER_ID_TYPE
  MP_PAYER_ID_NUMBER
)

# ─── Optional: written only when non-empty; code defaults apply otherwise ───
OPTIONAL=(
  ADMIN_BOOTSTRAP
  HOST_PORT
  CORS_ORIGINS
  CLOUDFLARE_TUNNEL_TOKEN
  DISCORD_ADMIN_ROLE_IDS
  PIX_EXPIRATION_MINUTES
  PURCHASE_SWEEP_INTERVAL_MS
  TICKET_INACTIVITY_HOURS
  RATE_LIMIT_COMMANDS
  RATE_LIMIT_BUY
  CREDITS_PER_BRL
  BUY_MIN_BRL
  BUY_MAX_BRL
)

MISSING=()
for var in "${REQUIRED[@]}"; do
  if [[ -z "${!var:-}" ]]; then
    MISSING+=("$var")
  fi
done

if (( ${#MISSING[@]} > 0 )); then
  {
    echo "materialize-env: missing required variables:"
    for var in "${MISSING[@]}"; do
      echo "  - $var"
    done
    echo
    echo "Set them as secrets in the target GitHub Actions Environment and re-run."
  } >&2
  exit 1
fi

# Docker Compose .env is one KEY=VALUE per line — newlines in a value would
# corrupt the file. Reject rather than silently truncate.
for var in "${REQUIRED[@]}" "${OPTIONAL[@]}"; do
  val="${!var:-}"
  if [[ "$val" == *$'\n'* || "$val" == *$'\r'* ]]; then
    echo "materialize-env: value for $var contains a newline; refusing to write" >&2
    exit 2
  fi
done

# Atomic write + strict perms.
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

{
  echo "# Generated by scripts/materialize-env.sh at $(date -u +%FT%TZ)"
  echo "# DO NOT COMMIT. Values sourced from the caller's process environment."
  echo
  echo "# ─── Required ────────────────────────────────────────────────────"
  for var in "${REQUIRED[@]}"; do
    printf '%s=%s\n' "$var" "${!var}"
  done
  echo
  echo "# ─── Optional (commented lines fall back to code defaults) ───────"
  for var in "${OPTIONAL[@]}"; do
    if [[ -n "${!var:-}" ]]; then
      printf '%s=%s\n' "$var" "${!var}"
    else
      printf '# %s=<using code default>\n' "$var"
    fi
  done
} > "$TMP"

mv "$TMP" "$OUTPUT"
chmod 600 "$OUTPUT"
trap - EXIT

WRITTEN=$(grep -c '^[A-Z]' "$OUTPUT" 2>/dev/null || echo 0)
echo "materialize-env: wrote $OUTPUT ($WRITTEN KEY=VALUE lines)"
