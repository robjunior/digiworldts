import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { INestApplication } from '@nestjs/common';
import { Test } from '@nestjs/testing';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { PrismaModule } from './prisma.module';
import { PrismaService } from './prisma.service';

/**
 * Persistence foundation contract (TASK-4, R-2). This is the runnable proof that
 * the app's FIRST datastore actually persists and reads back a record — the
 * enabling infra TASK-5's auth endpoints build on. It mirrors the house P-2 e2e
 * shape (boot a real Nest module via `Test.createTestingModule` + `app.init()`)
 * but against the datastore rather than an HTTP route.
 *
 * HERMETICITY (task friction #3, lesson L-3): the suite must NEVER touch the
 * shared `apps/api/prisma/dev.db`, and must be fast + deterministic. So it points
 * `DATABASE_URL` at a throwaway SQLite file in a per-run temp dir (absolute path,
 * so CLI and runtime resolve it identically — Prisma resolves a *relative* url
 * against the schema dir at CLI time but against CWD at runtime, which would
 * otherwise diverge), applies the schema to it with `prisma db push` (schema-only,
 * no migration history needed for a throwaway DB), runs the test, then deletes the
 * whole temp dir in `afterAll`. `DATABASE_URL` is set BEFORE `createApp`/module
 * construction because `PrismaService` reads it the moment `PrismaClient` is
 * constructed.
 */
describe('PrismaService (persistence e2e)', () => {
  let app: INestApplication;
  let prisma: PrismaService;
  let tmpDir: string;
  const originalDatabaseUrl = process.env.DATABASE_URL;

  beforeAll(async () => {
    // A unique temp dir per run so parallel/repeat runs never share a file.
    tmpDir = mkdtempSync(join(tmpdir(), 'digimon-api-test-'));
    const dbFile = join(tmpDir, 'test.db');
    process.env.DATABASE_URL = `file:${dbFile}`;

    // Create the schema in the throwaway DB. `db push` is the right tool here:
    // it syncs the schema without needing the committed migration history, which
    // keeps the gate independent of migration state. `--skip-generate` avoids
    // regenerating the client (already generated by install/build). Run from this
    // package dir so the schema is found; inherit the env so DATABASE_URL applies.
    execFileSync('pnpm', ['exec', 'prisma', 'db', 'push', '--skip-generate'], {
      cwd: join(__dirname, '..', '..'),
      env: process.env,
      stdio: 'pipe',
    });

    const moduleRef = await Test.createTestingModule({
      imports: [PrismaModule],
    }).compile();

    app = moduleRef.createNestApplication();
    await app.init(); // triggers PrismaService.onModuleInit -> $connect
    prisma = app.get(PrismaService);
  });

  afterAll(async () => {
    // Close the app first (PrismaService.onModuleDestroy -> $disconnect releases
    // the SQLite handle) THEN delete the temp DB, so no open file descriptor
    // lingers on the file we remove.
    await app?.close();
    if (tmpDir) rmSync(tmpDir, { recursive: true, force: true });
    if (originalDatabaseUrl === undefined) delete process.env.DATABASE_URL;
    else process.env.DATABASE_URL = originalDatabaseUrl;
  });

  it('persists a User row and reads it back', async () => {
    const email = `round-trip-${Date.now()}@example.test`;

    const created = await prisma.user.create({
      data: { email, passwordHash: 'not-a-real-hash-TASK-5-owns-hashing' },
    });

    // The write path populated the server-generated columns: a cuid id and a
    // createdAt default. deletedAt is the soft-delete marker and must be NULL for
    // a freshly created (active) account (invariant 2).
    expect(created.id).toBeTruthy();
    expect(typeof created.id).toBe('string');
    expect(created.email).toBe(email);
    expect(created.createdAt).toBeInstanceOf(Date);
    expect(created.deletedAt).toBeNull();

    // Read it back through a fresh query (not the create return value) to prove it
    // truly landed in — and comes back from — the datastore.
    const fetched = await prisma.user.findUnique({ where: { email } });
    expect(fetched).not.toBeNull();
    expect(fetched?.id).toBe(created.id);
    expect(fetched?.email).toBe(email);
    expect(fetched?.passwordHash).toBe('not-a-real-hash-TASK-5-owns-hashing');
  });

  it('enforces the unique email constraint at the datastore level', async () => {
    // Invariant realised in the schema (email @unique): a duplicate registration
    // must fail atomically in the DB, not race in app code. This is the guarantee
    // TASK-5's register endpoint will rely on.
    const email = `dupe-${Date.now()}@example.test`;
    await prisma.user.create({ data: { email, passwordHash: 'h1' } });

    await expect(prisma.user.create({ data: { email, passwordHash: 'h2' } })).rejects.toThrow();
  });
});
